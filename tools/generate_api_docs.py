#!/usr/bin/env python3
"""
Generate MkDocs + mkdocstrings API reference files for a Python project.

This script intentionally does not import your package. It traverses the source
 tree, discovers Python modules/packages, and writes Markdown files that use
mkdocstrings directives such as:

    ::: lboxdlib.session

That keeps API documentation generated from the live code/docstrings while
avoiding a hand-maintained API reference.

Typical use from the project root:

    python tools/generate_api_docs.py --src-dir src --package lboxdlib --write-mkdocs
    mkdocs serve

Recommended docs dependencies:

    pip install mkdocs mkdocs-material "mkdocstrings[python]"

Generated-file safety:

- Generated Markdown files include an HTML marker comment.
- A manifest is written to docs/api/.generated_api_docs_manifest.json.
- Stale generated files are pruned by default on later runs.
- For files generated by older versions of this script, run once with
  --clean-api-dir if docs/api is wholly generated content.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

try:  # Python 3.11+
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - only needed on Python < 3.11
    tomllib = None  # type: ignore[assignment]


DEFAULT_EXCLUDES = {
    ".git",
    ".hg",
    ".svn",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".tox",
    ".venv",
    "venv",
    "env",
    "build",
    "dist",
    "site",
    "docs",
    "tests",
    "test",
    "__pycache__",
}

DEFAULT_MODULE_EXCLUDES = {
    "setup",
    "conftest",
}

GENERATED_MARKER = "<!-- GENERATED BY tools/generate_api_docs.py; DO NOT EDIT BY HAND. -->"
MANIFEST_FILENAME = ".generated_api_docs_manifest.json"
MANIFEST_VERSION = 1


@dataclass(frozen=True, order=True)
class ModuleDoc:
    """A discovered Python module and its output documentation file."""

    module_name: str
    source_path: Path
    output_path: Path
    title: str
    is_package: bool


def _read_pyproject_name(project_root: Path) -> str | None:
    pyproject = project_root / "pyproject.toml"
    if not pyproject.exists() or tomllib is None:
        return None

    try:
        with pyproject.open("rb") as fh:
            data = tomllib.load(fh)
    except Exception:
        return None

    project = data.get("project", {})
    name = project.get("name")
    if isinstance(name, str) and name.strip():
        return name.strip().replace("-", "_")

    poetry = data.get("tool", {}).get("poetry", {})
    name = poetry.get("name")
    if isinstance(name, str) and name.strip():
        return name.strip().replace("-", "_")

    return None


def _looks_like_package(path: Path) -> bool:
    return path.is_dir() and (path / "__init__.py").exists()


def _candidate_package_dirs(project_root: Path, src_dir: Path | None = None) -> list[Path]:
    roots = [src_dir] if src_dir else [project_root / "src", project_root]
    candidates: list[Path] = []

    for root in roots:
        if root is None or not root.exists():
            continue
        for child in sorted(root.iterdir()):
            if child.name in DEFAULT_EXCLUDES or child.name.startswith("."):
                continue
            if _looks_like_package(child):
                candidates.append(child)

    return candidates


def resolve_package_dir(
    project_root: Path,
    package: str | None,
    src_dir: Path | None,
) -> tuple[str, Path]:
    """Resolve the package name and source directory to document."""

    search_roots = [src_dir] if src_dir else [project_root / "src", project_root]

    if package:
        package_path = Path(*package.split("."))
        for root in search_roots:
            if root is None or not root.exists():
                continue
            candidate = root / package_path
            if _looks_like_package(candidate):
                return package, candidate
        raise SystemExit(
            f"Could not find package {package!r}. Tried: "
            + ", ".join(str(root / package_path) for root in search_roots if root)
        )

    pyproject_name = _read_pyproject_name(project_root)
    if pyproject_name:
        package_path = Path(*pyproject_name.split("."))
        for root in search_roots:
            if root is None or not root.exists():
                continue
            candidate = root / package_path
            if _looks_like_package(candidate):
                return pyproject_name, candidate

    candidates = _candidate_package_dirs(project_root, src_dir)
    if len(candidates) == 1:
        return candidates[0].name, candidates[0]

    if not candidates:
        raise SystemExit(
            "Could not infer a Python package. Pass --package, for example: "
            "--package lboxdlib"
        )

    names = ", ".join(c.name for c in candidates)
    raise SystemExit(
        f"Multiple package candidates found ({names}). Pass --package explicitly."
    )


def _is_excluded_dir(path: Path, exclude_names: set[str]) -> bool:
    return path.name in exclude_names or path.name.startswith(".")


def _has_public_members(py_file: Path) -> bool:
    """Return True when a module appears to define public API members."""

    try:
        tree = ast.parse(py_file.read_text(encoding="utf-8"))
    except Exception:
        # If parsing fails, still document it; mkdocstrings will surface the issue.
        return True

    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.name.startswith("_"):
                return True
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "__all__":
                    return True
    return ast.get_docstring(tree) is not None


def discover_modules(
    package_name: str,
    package_dir: Path,
    docs_api_dir: Path,
    *,
    include_private: bool = False,
    include_empty: bool = False,
    exclude_dirs: Iterable[str] = DEFAULT_EXCLUDES,
    exclude_modules: Iterable[str] = DEFAULT_MODULE_EXCLUDES,
) -> list[ModuleDoc]:
    """Discover modules beneath package_dir and map them to Markdown files."""

    exclude_dir_names = set(exclude_dirs)
    exclude_module_names = set(exclude_modules)
    modules: list[ModuleDoc] = []

    for root, dirnames, filenames in os.walk(package_dir):
        root_path = Path(root)
        dirnames[:] = [
            d for d in dirnames
            if not _is_excluded_dir(root_path / d, exclude_dir_names)
            and (include_private or not d.startswith("_"))
        ]

        for filename in sorted(filenames):
            if not filename.endswith(".py"):
                continue

            py_file = root_path / filename
            stem = py_file.stem

            if stem in exclude_module_names:
                continue
            if not include_private and stem.startswith("_") and stem != "__init__":
                continue
            if not include_empty and not _has_public_members(py_file):
                continue

            rel = py_file.relative_to(package_dir)
            parts = list(rel.with_suffix("").parts)
            is_package = parts[-1] == "__init__"

            if is_package:
                module_parts = parts[:-1]
                module_name = package_name if not module_parts else f"{package_name}." + ".".join(module_parts)
                # Root package docs live at docs/api/package.md.
                # Subpackage docs live at docs/api/subpkg/index.md.
                if not module_parts:
                    output_path = docs_api_dir / f"{package_name}.md"
                    title = package_name
                else:
                    output_path = docs_api_dir.joinpath(*module_parts, "index.md")
                    title = module_name
            else:
                module_parts = parts
                module_name = f"{package_name}." + ".".join(module_parts)
                output_path = docs_api_dir.joinpath(*module_parts).with_suffix(".md")
                title = module_name

            modules.append(
                ModuleDoc(
                    module_name=module_name,
                    source_path=py_file,
                    output_path=output_path,
                    title=title,
                    is_package=is_package,
                )
            )

    return sorted(set(modules), key=lambda m: m.module_name)


def _relative_markdown_link(from_file: Path, to_file: Path) -> str:
    rel = os.path.relpath(to_file, start=from_file.parent)
    return rel.replace(os.sep, "/")


def _relative_to_api_dir(api_dir: Path, file_path: Path) -> str:
    return file_path.resolve().relative_to(api_dir.resolve()).as_posix()


def _root_export_names(init_file: Path) -> list[str]:
    """Return explicit package-root public exports for documentation.

    The package root uses PEP 562 lazy exports, which are valid runtime API but
    are easy for static documentation tools to under-display. This helper parses
    the root ``__init__.py`` without importing the package and extracts
    ``__version__`` plus the keys of ``_LAZY_EXPORTS`` so the generated root API
    page can document the public surface explicitly.
    """

    try:
        tree = ast.parse(init_file.read_text(encoding="utf-8"))
    except Exception:
        return []

    names: list[str] = []

    def handle_assignment_target(target: ast.expr, value: ast.expr | None) -> None:
        if not isinstance(target, ast.Name):
            return
        if target.id == "__version__":
            names.append("__version__")
            return
        if target.id == "_LAZY_EXPORTS" and isinstance(value, ast.Dict):
            for key in value.keys:
                if isinstance(key, ast.Constant) and isinstance(key.value, str):
                    names.append(key.value)

    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                handle_assignment_target(target, node.value)
        elif isinstance(node, ast.AnnAssign):
            handle_assignment_target(node.target, node.value)

    # Preserve source order while removing accidental duplicates.
    seen: set[str] = set()
    unique: list[str] = []
    for name in names:
        if name in seen:
            continue
        seen.add(name)
        unique.append(name)
    return unique


def _render_members_option(names: Sequence[str]) -> str:
    if not names:
        return ""
    lines = ["      members:"]
    lines.extend(f"        - {name}" for name in names)
    return "\n".join(lines) + "\n"


def render_api_page(module: ModuleDoc, *, show_source: bool, package_name: str) -> str:
    show_source_text = "true" if show_source else "false"
    root_members = _root_export_names(module.source_path) if module.module_name == package_name else []
    members_option = _render_members_option(root_members)

    page = (
        f"{GENERATED_MARKER}\n\n"
        f"# `{module.title}`\n\n"
    )

    if root_members:
        page += (
            "## Package-root public exports\n\n"
            "These names are intentionally exposed from the package root, so users can write "
            "compact imports such as `from lboxdlib import LBoxdSession, FilmHydrator`.\n\n"
        )
        page += "\n".join(f"- `{name}`" for name in root_members)
        page += "\n\n"

    page += (
        f"::: {module.module_name}\n"
        f"    options:\n"
        f"      show_source: {show_source_text}\n"
        f"      show_root_heading: true\n"
        f"      show_root_full_path: true\n"
        f"      members_order: source\n"
        f"{members_option}"
    )
    return page


def render_api_index(
    package_name: str,
    modules: Sequence[ModuleDoc],
    index_path: Path,
) -> str:
    lines = [
        GENERATED_MARKER,
        "",
        "# API Reference\n",
        f"Generated API reference for `{package_name}`.\n",
        "These Markdown files are generated from the source tree and rendered by `mkdocstrings`.\n",
        "## Modules\n",
    ]

    root_docs = [m for m in modules if m.module_name == package_name]
    other_docs = [m for m in modules if m.module_name != package_name]

    for module in root_docs + other_docs:
        link = _relative_markdown_link(index_path, module.output_path)
        lines.append(f"- [`{module.module_name}`]({link})")

    lines.append("")
    return "\n".join(lines)


def write_file(path: Path, content: str, *, dry_run: bool) -> None:
    if dry_run:
        print(f"would write {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def render_mkdocs_yml(project_name: str) -> str:
    return f"""site_name: {project_name}

theme:
  name: material

plugins:
  - search
  - mkdocstrings:
      handlers:
        python:
          options:
            docstring_style: google
            show_source: true
            show_signature_annotations: true
            separate_signature: true
            members_order: source
            filters:
              - '!^_'

nav:
  - Home: index.md
  - API Reference: api/index.md
"""


def _mkdocs_has_api_nav(text: str) -> bool:
    return bool(re.search(r"api/index\.md|API Reference", text))


def maybe_write_mkdocs_yml(
    project_root: Path,
    project_name: str,
    *,
    dry_run: bool,
    overwrite: bool,
) -> None:
    mkdocs_yml = project_root / "mkdocs.yml"
    content = render_mkdocs_yml(project_name)

    if not mkdocs_yml.exists():
        write_file(mkdocs_yml, content, dry_run=dry_run)
        return

    existing = mkdocs_yml.read_text(encoding="utf-8")
    if overwrite:
        backup = mkdocs_yml.with_suffix(".yml.bak")
        if dry_run:
            print(f"would back up {mkdocs_yml} to {backup}")
            print(f"would overwrite {mkdocs_yml}")
        else:
            backup.write_text(existing, encoding="utf-8")
            mkdocs_yml.write_text(content, encoding="utf-8")
            print(f"backed up {mkdocs_yml} to {backup}")
            print(f"wrote {mkdocs_yml}")
        return

    if _mkdocs_has_api_nav(existing):
        print(f"kept existing {mkdocs_yml}; it already appears to reference API docs")
    else:
        print(
            f"kept existing {mkdocs_yml}; add this nav entry if your nav is explicit:\n"
            "  - API Reference: api/index.md"
        )


def ensure_docs_index(docs_dir: Path, project_name: str, *, dry_run: bool) -> None:
    index = docs_dir / "index.md"
    if index.exists():
        return
    write_file(
        index,
        f"# {project_name}\n\nProject documentation.\n",
        dry_run=dry_run,
    )


def _manifest_path(docs_api_dir: Path) -> Path:
    return docs_api_dir / MANIFEST_FILENAME


def _read_manifest_files(docs_api_dir: Path) -> set[Path]:
    manifest = _manifest_path(docs_api_dir)
    if not manifest.exists():
        return set()

    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"warning: could not read generated-doc manifest {manifest}: {exc}")
        return set()

    files = data.get("files", [])
    if not isinstance(files, list):
        return set()

    result: set[Path] = set()
    for item in files:
        if not isinstance(item, str):
            continue
        result.add((docs_api_dir / item).resolve())
    return result


def _find_marked_generated_markdown_files(docs_api_dir: Path) -> set[Path]:
    if not docs_api_dir.exists():
        return set()

    result: set[Path] = set()
    for path in docs_api_dir.rglob("*.md"):
        try:
            head = path.read_text(encoding="utf-8", errors="ignore")[:512]
        except Exception:
            continue
        if GENERATED_MARKER in head:
            result.add(path.resolve())
    return result


def _assert_within_dir(parent: Path, child: Path) -> None:
    try:
        child.resolve().relative_to(parent.resolve())
    except ValueError as exc:
        raise RuntimeError(f"Refusing to modify file outside {parent}: {child}") from exc


def _delete_file(path: Path, *, dry_run: bool) -> bool:
    if not path.exists():
        return False
    if dry_run:
        print(f"would delete stale generated file {path}")
        return True
    path.unlink()
    print(f"deleted stale generated file {path}")
    return True


def _remove_empty_dirs(root: Path, *, dry_run: bool) -> None:
    if not root.exists():
        return

    dirs = sorted((p for p in root.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True)
    for directory in dirs:
        try:
            next(directory.iterdir())
            continue
        except StopIteration:
            pass
        except OSError:
            continue

        if dry_run:
            print(f"would remove empty directory {directory}")
        else:
            try:
                directory.rmdir()
                print(f"removed empty directory {directory}")
            except OSError:
                pass


def clean_api_dir(docs_api_dir: Path, *, dry_run: bool) -> None:
    """Delete existing generated Markdown files before regeneration.

    This intentionally removes Markdown files beneath docs_api_dir, even if they
    were produced by an older generator that did not write a manifest/marker.
    It does not touch hand-written docs outside docs_api_dir.
    """

    if not docs_api_dir.exists():
        return

    print(f"cleaning generated API Markdown files below {docs_api_dir}")
    for path in sorted(docs_api_dir.rglob("*.md")):
        _assert_within_dir(docs_api_dir, path)
        if dry_run:
            print(f"would delete generated API file {path}")
        else:
            path.unlink()
            print(f"deleted generated API file {path}")

    manifest = _manifest_path(docs_api_dir)
    if manifest.exists():
        _assert_within_dir(docs_api_dir, manifest)
        if dry_run:
            print(f"would delete generated-doc manifest {manifest}")
        else:
            manifest.unlink()
            print(f"deleted generated-doc manifest {manifest}")

    _remove_empty_dirs(docs_api_dir, dry_run=dry_run)


def prune_stale_generated_files(
    docs_api_dir: Path,
    desired_files: set[Path],
    *,
    dry_run: bool,
) -> None:
    """Delete generated Markdown files that no longer correspond to modules."""

    if not docs_api_dir.exists():
        return

    desired_resolved = {p.resolve() for p in desired_files}
    known_generated = _read_manifest_files(docs_api_dir)
    known_generated.update(_find_marked_generated_markdown_files(docs_api_dir))

    stale = sorted(p for p in known_generated if p not in desired_resolved)
    if not stale:
        return

    print(f"pruning {len(stale)} stale generated file(s) below {docs_api_dir}")
    for path in stale:
        _assert_within_dir(docs_api_dir, path)
        _delete_file(path, dry_run=dry_run)

    _remove_empty_dirs(docs_api_dir, dry_run=dry_run)


def write_manifest(
    docs_api_dir: Path,
    package_name: str,
    desired_files: set[Path],
    *,
    dry_run: bool,
) -> None:
    files = sorted(_relative_to_api_dir(docs_api_dir, p) for p in desired_files)
    data = {
        "version": MANIFEST_VERSION,
        "generator": "tools/generate_api_docs.py",
        "package": package_name,
        "files": files,
    }
    content = json.dumps(data, indent=2, sort_keys=True) + "\n"
    write_file(_manifest_path(docs_api_dir), content, dry_run=dry_run)


def generate_docs(args: argparse.Namespace) -> int:
    project_root = args.project_root.resolve()
    src_dir = args.src_dir.resolve() if args.src_dir else None
    docs_dir = (project_root / args.docs_dir).resolve()
    docs_api_dir = (docs_dir / args.api_dir).resolve()

    package_name, package_dir = resolve_package_dir(project_root, args.package, src_dir)
    modules = discover_modules(
        package_name,
        package_dir,
        docs_api_dir,
        include_private=args.include_private,
        include_empty=args.include_empty,
        exclude_dirs=set(DEFAULT_EXCLUDES).union(args.exclude_dir),
        exclude_modules=set(DEFAULT_MODULE_EXCLUDES).union(args.exclude_module),
    )

    if not modules:
        raise SystemExit(f"No modules discovered below {package_dir}")

    print(f"project root: {project_root}")
    print(f"package:      {package_name} ({package_dir})")
    print(f"docs output:  {docs_api_dir}")
    print(f"modules:      {len(modules)}")

    index_path = docs_api_dir / "index.md"
    desired_files = {index_path.resolve()}
    desired_files.update(module.output_path.resolve() for module in modules)

    if args.clean_api_dir:
        clean_api_dir(docs_api_dir, dry_run=args.dry_run)
    elif args.prune:
        prune_stale_generated_files(docs_api_dir, desired_files, dry_run=args.dry_run)

    ensure_docs_index(docs_dir, args.site_name or package_name, dry_run=args.dry_run)

    write_file(
        index_path,
        render_api_index(package_name, modules, index_path),
        dry_run=args.dry_run,
    )

    for module in modules:
        write_file(
            module.output_path,
            render_api_page(module, show_source=not args.hide_source, package_name=package_name),
            dry_run=args.dry_run,
        )

    write_manifest(
        docs_api_dir,
        package_name,
        desired_files,
        dry_run=args.dry_run,
    )

    if args.write_mkdocs:
        maybe_write_mkdocs_yml(
            project_root,
            args.site_name or package_name,
            dry_run=args.dry_run,
            overwrite=args.overwrite_mkdocs,
        )

    print("\nNext steps:")
    print('  pip install mkdocs mkdocs-material "mkdocstrings[python]"')
    print("  mkdocs serve")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate MkDocs/mkdocstrings API Markdown files for a Python package.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path.cwd(),
        help="Project root. Defaults to the current working directory.",
    )
    parser.add_argument(
        "--src-dir",
        type=Path,
        default=None,
        help="Optional source root, for example ./src.",
    )
    parser.add_argument(
        "--package",
        default=None,
        help="Package import name to document, for example lboxdlib. "
        "If omitted, the script tries pyproject.toml and then package discovery.",
    )
    parser.add_argument(
        "--docs-dir",
        default="docs",
        help="Docs directory relative to project root. Default: docs.",
    )
    parser.add_argument(
        "--api-dir",
        default="api",
        help="Generated API docs directory relative to docs dir. Default: api.",
    )
    parser.add_argument(
        "--site-name",
        default=None,
        help="Site name to use when creating mkdocs.yml or docs/index.md.",
    )
    parser.add_argument(
        "--write-mkdocs",
        action="store_true",
        help="Create mkdocs.yml if missing. Existing mkdocs.yml is kept unless --overwrite-mkdocs is used.",
    )
    parser.add_argument(
        "--overwrite-mkdocs",
        action="store_true",
        help="Overwrite existing mkdocs.yml after writing mkdocs.yml.bak.",
    )
    parser.add_argument(
        "--include-private",
        action="store_true",
        help="Include private modules/packages whose names start with underscore.",
    )
    parser.add_argument(
        "--include-empty",
        action="store_true",
        help="Include modules even if they appear to have no public members/docstring.",
    )
    parser.add_argument(
        "--hide-source",
        action="store_true",
        help="Hide source links/code blocks in generated mkdocstrings files.",
    )
    parser.add_argument(
        "--exclude-dir",
        action="append",
        default=[],
        help="Additional directory name to exclude. Can be passed multiple times.",
    )
    parser.add_argument(
        "--exclude-module",
        action="append",
        default=[],
        help="Additional module stem to exclude, for example cli. Can be passed multiple times.",
    )
    parser.add_argument(
        "--prune",
        dest="prune",
        action="store_true",
        default=True,
        help="Delete stale generated Markdown files recorded in the manifest or marker comments. Enabled by default.",
    )
    parser.add_argument(
        "--no-prune",
        dest="prune",
        action="store_false",
        help="Do not delete stale generated Markdown files.",
    )
    parser.add_argument(
        "--clean-api-dir",
        action="store_true",
        help=(
            "Before generating, delete existing Markdown files below docs/api and the generated-doc manifest. "
            "Use once to clean files generated by older versions of this script, but only if docs/api is generated content."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be written/deleted without changing files.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return generate_docs(args)


if __name__ == "__main__":
    raise SystemExit(main())
